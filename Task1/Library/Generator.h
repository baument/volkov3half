#pragma once

namespace miit::algebra
{
    /**
     * @brief Абстрактный базовый класс генератора значений.
     *
     * Matrix не должна знать, ОТКУДА пришло очередное число.
     * Она знает только одно: у любого Generator есть метод generate().
     * Конкретный способ получения числа задаётся в классах-наследниках.
     */
    class Generator
    {
    public:
        /**
         * @brief Виртуальный деструктор.
         *
         * Он нужен, потому что Generator используется как базовый класс.
         * = 0 делает деструктор чисто виртуальным, но реализация всё равно
         * будет дана в Generator.cpp.
         */
        virtual ~Generator() = 0;

        /**
         * @brief Получить следующее целое значение.
         * @return Сгенерированное значение.
         *
         * Метод чисто виртуальный: каждый наследник обязан определить,
         * как именно он получает число.
         */
        virtual int generate() = 0;
    };
}
